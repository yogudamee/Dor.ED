import { CadEntity, PresetCase } from '../../types/cad';

function makeLine(
  id: string,
  view: 'front' | 'top' | 'left',
  u1: number,
  v1: number,
  u2: number,
  v2: number,
  lineType: 'thick_solid' | 'thin_dashed' | 'center_dot_dash' = 'thick_solid'
): CadEntity {
  return {
    id,
    view,
    type: 'line',
    lineType,
    p1: { u: u1, v: v1 },
    p2: { u: u2, v: v2 },
    source: 'template',
  };
}

function makeRect(
  id: string,
  view: 'front' | 'top' | 'left',
  x: number,
  y: number,
  w: number,
  h: number,
  lineType: 'thick_solid' | 'thin_dashed' = 'thick_solid'
): CadEntity {
  return {
    id,
    view,
    type: 'rect',
    lineType,
    x,
    y,
    width: w,
    height: h,
    source: 'template',
  };
}

function makeCircle(
  id: string,
  view: 'front' | 'top' | 'left',
  cu: number,
  cv: number,
  r: number,
  lineType: 'thick_solid' | 'thin_dashed' = 'thick_solid'
): CadEntity {
  return {
    id,
    view,
    type: 'circle',
    lineType,
    center: { u: cu, v: cv },
    radius: r,
    source: 'template',
  };
}

function makeArc(
  id: string,
  view: 'front' | 'top' | 'left',
  cu: number,
  cv: number,
  r: number,
  startAngle: number,
  endAngle: number,
  lineType: 'thick_solid' | 'thin_dashed' = 'thick_solid'
): CadEntity {
  return {
    id,
    view,
    type: 'arc',
    lineType,
    center: { u: cu, v: cv },
    radius: r,
    startAngle,
    endAngle,
    source: 'template',
  };
}

function makePoly(
  id: string,
  view: 'front' | 'top' | 'left',
  pts: [number, number][],
  closed = true,
  lineType: 'thick_solid' | 'thin_dashed' = 'thick_solid'
): CadEntity {
  return {
    id,
    view,
    type: 'polygon',
    lineType,
    points: pts.map(([u, v]) => ({ u, v })),
    closed,
    source: 'template',
  };
}

