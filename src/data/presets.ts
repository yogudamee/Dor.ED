export function getLocalizedPresets(lang: 'zh-CN' | 'zh-TW' | 'en'): PresetCase[] {
  if (lang === 'zh-CN') return PRESET_CASES;
  const map = PRESET_TRANSLATIONS[lang];
  return PRESET_CASES.map((preset) => {
    const loc = map[preset.id];
    if (!loc) return preset;
    return {
      ...preset,
      name: loc.name,
      badge: loc.badge,
      description: loc.description,
      solutions: preset.solutions.map((sol) => {
        const sLoc = loc.solutions[sol.id];
        if (!sLoc) return sol;
        return {
          ...sol,
          title: sLoc.title,
          subtitle: sLoc.subtitle,
          description: sLoc.description,
          confidence: sLoc.confidence,
          projectionSteps: sol.projectionSteps.map((st) => {
            const stLoc = sLoc.steps?.[st.id];
            if (!stLoc) return st;
            return {
              ...st,
              title: stLoc.title,
              description: stLoc.description,
            };
          }),
        };
      }),
    };
  });
}

